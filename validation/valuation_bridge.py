"""Old-to-new per-share bridge from the frozen October 6 values, low/base/high.

Code corrections (adopted, because they fix calculation errors) are applied in sequence.
Discretionary assumption options are NOT adopted: each is shown alone against the corrected
model so Pierce can see its per-share effect before deciding. Writes
outputs/valuation_bridge.csv and docs/valuation-bridge-2026-10-20.md.
Usage: python -m validation.valuation_bridge
"""
import copy
from pathlib import Path

from src.model import dump_csv, forecast, load, value
from src.taxes import nol_value

CORRECTIONS = [
    ("cutoff_cash_rollforward", "Code correction: roll June 30 cash to October 5 with retained stub cash"),
    ("award_runoff_schedule", "Code correction: capped existing-award runoff schedule (RSUs to June 2029; filed option period)"),
]


def case_value(config, data, name, fade_years=None, case_changes=None):
    """Per-share value of one case under a modified configuration."""
    case = copy.deepcopy(config["cases"][name])
    case.update(case_changes or {})
    rows = forecast(case, data, config)
    return value(rows, case, data, config, fade_years=fade_years)["per_share"]


def wacc_for_beta(config, beta):
    """Cost of equity (= WACC with no debt) for an alternative beta."""
    capital = config["capital_cost"]
    return capital["riskfree"] + beta * capital["erp"]


def bridge_rows():
    """Return bridge rows for every case."""
    data, config = load()
    rows = []
    for name in config["cases"]:
        frozen = copy.deepcopy(config)
        frozen["corrections"] = {key: False for key, _ in CORRECTIONS}
        previous = case_value(frozen, data, name)
        rows.append(dict(case=name, kind="frozen", step="Frozen October 6 model (7c190eb)", per_share=previous, change=0.0, adopted="historical"))
        running = frozen
        for key, label in CORRECTIONS:
            running = copy.deepcopy(running)
            running["corrections"][key] = True
            current = case_value(running, data, name)
            rows.append(dict(case=name, kind="code correction", step=label, per_share=current, change=current - previous, adopted="yes"))
            previous = current
        corrected = previous
        rows.append(dict(case=name, kind="subtotal", step="Corrected model (current base convention)", per_share=corrected, change=0.0, adopted="yes"))

        options = []
        for years in [5, 10]:
            options.append((f"Option: {years}-year linear fade before maturity", case_value(config, data, name, fade_years=years)))
        held = copy.deepcopy(config["cases"][name]["margins"])
        flat = [held[0]] * 5
        options.append(("Option: hold 2026 input margin flat through 2030 (terminal margin unchanged)", case_value(config, data, name, case_changes={"margins": flat})))
        case = config["cases"][name]
        case_rows = forecast(case, data, config)
        for availability in [0.5, 1.0]:
            nol, _ = nol_value(case_rows, case, data, config, availability)
            options.append((f"Option: NOL tax shield, {availability:.0%} of pools usable", corrected + nol["per_share"]))
        if name == "base":
            for beta in [1.0, 1.5, 2.0]:
                wacc = wacc_for_beta(config, beta)
                options.append((f"Option: beta {beta:.2f} (WACC {wacc:.2%}), hypothetical, not a sourced estimate", case_value(config, data, name, case_changes={"wacc": wacc})))
        for label, amount in options:
            rows.append(dict(case=name, kind="assumption option", step=label, per_share=amount, change=amount - corrected, adopted="no: awaiting Pierce"))
    return rows


def markdown(rows):
    """Render the bridge in the same table format as docs/prior-work-comparison.md."""
    lines = [
        "# Old-to-new valuation bridge (post-comparison revision, Claude Code, 2026-10-20)",
        "",
        "Generated by `python -m validation.valuation_bridge`. Values are USD per diluted economic share.",
        "Code corrections are applied in sequence and adopted. Assumption options are **not adopted**:",
        "each is shown alone against the corrected model, so the changes are not additive.",
        "",
    ]
    for name in ["low", "base", "high"]:
        lines += [f"## {name.capitalize()} case", "", "| Step | Kind | Value/share | Change | Adopted |", "|---|---|---:|---:|---|"]
        for row in [x for x in rows if x["case"] == name]:
            lines.append(f"| {row['step']} | {row['kind']} | ${row['per_share']:.2f} | {row['change']:+.2f} | {row['adopted']} |")
        lines.append("")
    lines += [
        "The October 5, 2026 price is $189.40. No option above, alone, brings any case near that price.",
        "Order matters for the corrections: the cutoff-cash step uses the frozen award schedule; the award step then uses rolled cash.",
    ]
    return "\n".join(lines) + "\n"


def main():
    rows = bridge_rows()
    dump_csv("outputs/valuation_bridge.csv", rows)
    Path("docs/valuation-bridge-2026-10-20.md").write_text(markdown(rows), encoding="utf8")
    for row in rows:
        print(f"{row['case']:5} {row['per_share']:8.2f} {row['change']:+7.2f}  {row['step']}")


if __name__ == "__main__":
    main()
